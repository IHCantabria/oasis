function plotBox(dim,pos,color)

a = dim(1);
b = dim(2);
c = dim(3);

X = [0.5*a 0.5*a 0.5*a 0.5*a; ...
     -0.5*a -0.5*a -0.5*a -0.5*a; ...
     0.5*a 0.5*a -0.5*a -0.5*a; ...
     0.5*a 0.5*a -0.5*a -0.5*a; ...
     0.5*a -0.5*a -0.5*a 0.5*a; ...
     0.5*a -0.5*a -0.5*a 0.5*a;]';
 
Y = [0.5*b -0.5*b -0.5*b 0.5*b; ...
     0.5*b -0.5*b -0.5*b 0.5*b; ...
     0.5*b 0.5*b 0.5*b 0.5*b; ...
     -0.5*b -0.5*b -0.5*b -0.5*b; ...
     0.5*b 0.5*b -0.5*b -0.5*b; ...
     0.5*b 0.5*b -0.5*b -0.5*b;]';
 
Z = [0.5*c 0.5*c -0.5*c -0.5*c; ...
     0.5*c 0.5*c -0.5*c -0.5*c; ...
     0.5*c -0.5*c -0.5*c 0.5*c; ...
     0.5*c -0.5*c -0.5*c 0.5*c; ...
     0.5*c 0.5*c 0.5*c 0.5*c; ...
     -0.5*c -0.5*c -0.5*c -0.5*c;]';
 
 roll = pos(4);
 pitch = pos(5);
 yaw = pos(6);
 
 Mrot = [ cosd(pitch)*cosd(yaw), cosd(yaw)*sind(pitch)*sind(roll) - cosd(roll)*sind(yaw), sind(roll)*sind(yaw) + cosd(roll)*cosd(yaw)*sind(pitch); ...
        cosd(pitch)*sind(yaw), cosd(roll)*cosd(yaw) + sind(pitch)*sind(roll)*sind(yaw), cosd(roll)*sind(pitch)*sind(yaw) - cosd(yaw)*sind(roll); ...
         -sind(pitch),                               cosd(pitch)*sind(roll),                               cosd(pitch)*cosd(roll)];
     
 for i = 1:size(X,1)
     for j = 1:size(X,2)
         v = [X(i,j);Y(i,j);Z(i,j)];
         v = Mrot*v;
         X(i,j) = v(1);
         Y(i,j) = v(2);
         Z(i,j) = v(3);
     end
 end
 
 X = X + ones(size(X))*pos(1);
 Y = Y + ones(size(Y))*pos(2);
 Z = Z + ones(size(Z))*pos(3);
 
 fill3(X,Y,Z,color)

end